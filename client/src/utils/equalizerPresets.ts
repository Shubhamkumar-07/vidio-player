export function getPresetBands(name: string): { [freq: number]: number } {
  const gains = EQ_PRESETS[name] || EQ_PRESETS['Flat'];
  const bands: { [freq: number]: number } = {};
  EQ_FREQUENCIES.forEach((freq, idx) => {
    bands[freq] = gains[idx];
  });
  return bands;
}
